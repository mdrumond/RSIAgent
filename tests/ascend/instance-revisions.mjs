import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp,mkdir,writeFile,readFile,rm } from 'node:fs/promises';
import { join,resolve,isAbsolute } from 'node:path';
import { tmpdir } from 'node:os';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import { DatabaseSync } from 'node:sqlite';
import { bootstrap,readConfig,updateConfig } from '../../cli/instance.mjs';
import { copyVersion } from '../../cli/skill-input.mjs';
import { main } from '../../cli/main.mjs';
import { stages } from '../../controller/workflow.mjs';
import { processIdentity,ownerStopped } from '../../controller/lifecycle.mjs';
async function fixture(t,{seed=false}={}) {
  const root=await mkdtemp(join(tmpdir(),'ascend-config-'));t.after(()=>rm(root,{recursive:true,force:true}));
  const baseline=join(root,'baseline.sqlite'),db=new DatabaseSync(baseline);
  db.exec("CREATE TABLE evidence(value); INSERT INTO evidence VALUES (42)");db.close();
  const skills=join(root,'input-skills');await mkdir(skills);
  const map=Object.fromEntries(['global-kdb',...stages].map(scope=>[scope,join(skills,scope+'.md')]));
  for(const file of Object.values(map))await writeFile(file,'independent evidence');
  await writeFile(join(skills,'skill-map.json'),JSON.stringify(map));
  const machinery=join(root,'release');await mkdir(machinery);
  const projects=[];
  if(seed) {
    const source=join(root,'input');await mkdir(source);await writeFile(join(source,'answer.py'),'answer=42');
    const verifier=join(root,'verify.py');await writeFile(verifier,'assert 6*7==42');
    projects.push({id:'seed',goal:'numeric answer',actor_seconds:240,source,verifier:{command:'python ../verify.py',files:[verifier]}});
  }
  const instance=join(root,'instance');await bootstrap(instance,{baseline,skills,machinery,projects,install:false,environment:{options:{mode:'local'}}});
  return {root,instance,skills};
}
test('bootstrap initializes queued projects before any wave or status reader',async t=>{
  const {instance}=await fixture(t,{seed:true});
  const db=new DatabaseSync(join(instance,'state.sqlite'),{readOnly:true});
  assert.equal(db.prepare('PRAGMA user_version').get().user_version,1);db.close();
  const status=await main(['status','--instance',instance]);
  assert.equal(status.projects.length,1);
  assert.deepEqual({...status.projects[0]},{id:'seed',status:'queued',frozen:0,actor_seconds:240,goal:'numeric answer'});
  assert.deepEqual(status.attempts,[]);
  assert.equal(status.controller.state,'stopped');
});
test('stale baseline save leaves live memory and its service owner untouched',async t=>{
  const f=await fixture(t),before=await readConfig(f.instance);
  const child=spawn(process.execPath,['-e','setInterval(()=>{},1000)'],{stdio:'ignore'});
  await once(child,'spawn');const owner=await processIdentity(child.pid);
  t.after(async()=>{if(child.exitCode===null && child.signalCode===null){const closed=once(child,'exit');child.kill();await closed;}});
  const receipt=JSON.stringify({url:'http://127.0.0.1:1/mcp',owner});
  await writeFile(join(f.instance,'knowledge-service.json'),receipt);
  await updateConfig(f.instance,c=>({...c,concurrency:2}));
  const replacement=join(f.root,'replacement.sqlite'),db=new DatabaseSync(replacement);
  db.exec("CREATE TABLE evidence(value); INSERT INTO evidence VALUES (7)");db.close();
  const input=join(f.root,'stale.json');await writeFile(input,JSON.stringify({...before,baselineKDB:replacement}));
  await assert.rejects(main(['config','--instance',f.instance,'--config',input]),/Inputs changed/);
  const memory=new DatabaseSync(join(f.instance,'knowledge.sqlite'),{readOnly:true});
  assert.equal(memory.prepare('SELECT value FROM evidence').get().value,42);memory.close();
  assert.equal(await readFile(join(f.instance,'knowledge-service.json'),'utf8'),receipt);
  assert.equal(await ownerStopped(owner),false);
  assert.equal((await readConfig(f.instance)).baselineKDB,before.baselineKDB);
  await writeFile(input,JSON.stringify({...await readConfig(f.instance),baselineKDB:replacement}));
  await main(['config','--instance',f.instance,'--config',input]);
  const replaced=new DatabaseSync(join(f.instance,'knowledge.sqlite'),{readOnly:true});
  assert.equal(replaced.prepare('SELECT value FROM evidence').get().value,7);replaced.close();
  assert.equal((await readConfig(f.instance)).baselineKDB,replacement);
});
test('absolute in-root skill maps become independent relative version snapshots',async t=>{
  const f=await fixture(t);await rm(f.skills,{recursive:true});
  const config=await readConfig(f.instance),baseline=join(f.instance,'skills/versions/baseline');
  const map=JSON.parse(await readFile(join(baseline,'skill-map.json'),'utf8'));
  assert.ok(Object.values(map).every(value=>!isAbsolute(value)));
  const absolute=Object.fromEntries(Object.entries(map).map(([scope,path])=>[scope,resolve(baseline,path)]));
  const outside=join(f.root,'outside.md');await writeFile(outside,'outside');
  await assert.rejects(copyVersion(config,{...absolute,design:outside}),/immutable version/);
  const version=await copyVersion(config,absolute,{scope:'design',content:'new independent design'});
  assert.equal(await readFile(absolute.design,'utf8'),'independent evidence');
  await rm(baseline,{recursive:true});
  const directory=join(f.instance,'skills/versions',version),next=JSON.parse(await readFile(join(directory,'skill-map.json'),'utf8'));
  assert.equal(await readFile(resolve(directory,next.design),'utf8'),'new independent design');
  assert.equal(await readFile(resolve(directory,next.debug),'utf8'),'independent evidence');
});
test('status reports controller identity independently of project rows',async t=>{
  const f=await fixture(t);
  assert.deepEqual((await main(['status','--instance',f.instance])).controller,{state:'stopped',wave:0,stopRequested:false});
  const db=new DatabaseSync(join(f.instance,'state.sqlite'));db.exec('CREATE TABLE control(key TEXT PRIMARY KEY,value TEXT NOT NULL)');
  const set=(key,value)=>db.prepare('INSERT OR REPLACE INTO control VALUES (?,?)').run(key,JSON.stringify(value));
  const owner=await processIdentity();set('owner',owner);set('wave',3);set('stop',false);
  assert.deepEqual((await main(['status','--instance',f.instance])).controller,{state:'running',wave:3,stopRequested:false});
  set('owner',{...owner,start:'different-owner'});set('stop',true);
  assert.equal((await main(['status','--instance',f.instance])).controller.state,'stopped');
  set('owner',{pid:owner.pid});
  assert.equal((await main(['status','--instance',f.instance])).controller.state,'unknown');db.close();
});
